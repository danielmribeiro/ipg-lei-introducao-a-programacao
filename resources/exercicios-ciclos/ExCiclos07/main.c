#include <stdio.h>

/****************************************************************************
 *                                                                          *
 * Function: main                                                           *
 *                                                                          *
 * Purpose : Main entry point.                                              *
 *                                                                          *
 * History : Date      Reason                                               *
 *           00/00/00  Created                                              *
 *                                                                          *
 ****************************************************************************/

int main(int argc, char *argv[])
{
    int n, j, linha;

	printf("Input? ");
	scanf("%d",&n);

	printf("Linha? ");
	scanf("%d",&linha);

	
	for (j=0;j<n;j++){
		printf("%d,%d  ",linha,j);
	}
	printf("\n");
	
    return 0;
}

