#include <stdio.h>

/****************************************************************************
 *                                                                          *
 * Function: main                                                           *
 *                                                                          *
 * Purpose : Main entry point.                                              *
 *                                                                          *
 * History : Date      Reason                                               *
 *           00/00/00  Created                                              *
 *                                                                          *
 ****************************************************************************/

int main(int argc, char *argv[])
{
    int n, i, j;

	printf("Input? ");
	scanf("%d",&n);

	for (i=0;i<n;i++){
		for (j=0;j<n;j++){
			printf("%d,%d  ",i,j);
		}
		printf("\n");
	}

    return 0;
}

